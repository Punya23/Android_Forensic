# ---------------------------------------------------------------------------
# Address normalisation
# ---------------------------------------------------------------------------


def normalise_mac(mac: str) -> str:
    """Return ``AA:BB:CC:DD:EE:FF`` (uppercase, colon-separated), or ``""``.

    Accepts colon-, hyphen-, dot- or space-separated forms and bare 12-hex
    strings.  Returns the empty string for anything that is not a well-formed
    48-bit address — callers must treat ``""`` as "not a MAC", never as a
    zero address.
    """
    if not mac or not isinstance(mac, str):
        return ""
    compact = _MAC_SEP_RE.sub("", mac.strip()).upper()
    if not _HEX12_RE.match(compact):
        return ""
    return ":".join(compact[i : i + 2] for i in range(0, 12, 2))


def oui_prefix(mac: str) -> str:
    """Return the 24-bit OUI as 6 uppercase hex chars (``"AABBCC"``), or ``""``."""
    norm = normalise_mac(mac)
    if not norm:
        return ""
    return norm.replace(":", "")[:6]


def _first_octet(mac: str) -> Optional[int]:
    norm = normalise_mac(mac)
    if not norm:
        return None
    return int(norm[0:2], 16)


def is_locally_administered(mac: str) -> bool:
    """True if bit 1 of the first octet is set (locally administered address).

    Such an address was assigned by the local administrator / generated by the
    device, so it is not present in the IEEE registry at all and any OUI
    "match" against it is coincidental.
    """
    octet = _first_octet(mac)
    return octet is not None and bool(octet & 0x02)


def is_multicast(mac: str) -> bool:
    """True if bit 0 of the first octet is set (group/multicast address).

    Never valid as a Bluetooth device address; its presence indicates a parsing
    error or a corrupted record.
    """
    octet = _first_octet(mac)
    return octet is not None and bool(octet & 0x01)


def random_address_subtype(mac: str) -> str:
    """Classify a Bluetooth LE *random* address by its two most-significant bits.

    ``"static"``          — 0b11: random but stable for the peer's power cycle.
    ``"resolvable"``      — 0b01: Resolvable Private Address, rotates (~15 min).
    ``"non_resolvable"``  — 0b00: fully random, rotates.
    ``"reserved"``        — 0b10: not defined by the Core Spec.
    ``"invalid"``         — the input was not a MAC.

    None of these carry registry meaning; this function exists so the report can
    say *why* an OUI lookup was refused.
    """
    octet = _first_octet(mac)
    if octet is None:
        return "invalid"
    top = (octet >> 6) & 0x03
    return {0: "non_resolvable", 1: "resolvable", 2: "reserved", 3: "static"}[top]


# ---------------------------------------------------------------------------
# Lookup
# ---------------------------------------------------------------------------


def lookup_reason(mac: str, *, addr_type: Optional[int] = None) -> tuple[bool, str]:
    """Return ``(applicable, reason)`` for an OUI lookup on ``mac``.

    Exposed separately from :func:`lookup_vendor` so the report can print the
    *reason* a vendor field is blank instead of leaving the reader to guess.
    """
    norm = normalise_mac(mac)
    if not norm:
        return False, "not a valid 48-bit address"
    if norm == "00:00:00:00:00:00":
        return False, "all-zero address (controller address not yet read)"
    # AddrType 1 = random, 3 = random identity. Both are peer-generated values
    # with no IEEE registry meaning. Refusing here is the whole point.
    if addr_type in (1, 3):
        subtype = random_address_subtype(norm)
        return False, f"random address ({subtype}) — carries no IEEE OUI"
    if addr_type == 0xFF:
        return False, "anonymous address — carries no IEEE OUI"
    if is_multicast(norm):
        return False, "group/multicast bit set — not a valid device address"
    if is_locally_administered(norm):
        return False, "locally administered address — not in the IEEE registry"
    return True, "public address — IEEE MA-L lookup applicable"


def lookup_vendor(mac: str, *, addr_type: Optional[int] = None) -> Optional[str]:
    """Return the IEEE MA-L registered assignee for ``mac``, or ``None``.

    ``None`` is returned — deliberately, and without guessing — when:

    * ``addr_type`` is 1 (random) or 3 (random identity): the address was
      generated by the peer, so an OUI lookup would be a fabricated finding;
    * ``addr_type`` is 0xFF (anonymous);
    * the address is locally administered, multicast, all-zero or malformed;
    * the prefix is simply not in the pruned offline table.

    The distinction between those cases is available via :func:`lookup_reason`.
    """
    applicable, _reason = lookup_reason(mac, addr_type=addr_type)
    if not applicable:
        return None
    return OUI_TABLE.get(oui_prefix(mac))


def describe_vendor(mac: str, *, addr_type: Optional[int] = None) -> dict:
    """Full, self-documenting lookup result for embedding in a report row."""
    applicable, reason = lookup_reason(mac, addr_type=addr_type)
    vendor = OUI_TABLE.get(oui_prefix(mac)) if applicable else None
    return {
        "applicable": applicable,
        "reason": reason,
        "oui": oui_prefix(mac),
        "assignee": vendor,
        "registry": OUI_REGISTRY_NAME,
        "snapshot_date": OUI_REGISTRY_SNAPSHOT,
        # Phrasing matters: the assignee registered the address block. It is not
        # a claim about who manufactured or branded the product.
        "phrasing": (
            f"registered assignee of OUI {oui_prefix(mac)}" if vendor else ""
        ),
        "table_is_subset": True,
    }
