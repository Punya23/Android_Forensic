"""IEEE OUI (MAC vendor prefix) lookup — offline, snapshot-versioned.

Forensic purpose
----------------
The first three octets of an IEEE-802 EUI-48 address are the Organisationally
Unique Identifier (OUI) assigned by the IEEE Registration Authority.  For a
*public* Bluetooth device address this lets us name the party that registered
the address block, which is often the only vendor attribution available for a
peer device whose friendly ``Name`` is peer-supplied (and therefore unverified).

Limitations — read these before quoting a result in a report
------------------------------------------------------------
* An OUI identifies the **registered assignee of the address block**, i.e. the
  silicon / module vendor or the company that bought the block.  It is NOT
  proof of the brand printed on the product.  Results are phrased as
  "registered assignee of OUI xx:xx:xx".
* Lookup is only meaningful for **public** addresses.  A Bluetooth LE *random*
  address (``AddrType`` 1 or 3) is generated by the peer and carries no
  registry meaning whatsoever — :func:`lookup_vendor` refuses those and
  returns ``None``.  Reporting "Apple, Inc." because a random address happens
  to fall inside a registered range is a fabricated finding.
* A **locally administered** address (bit 1 of the first octet set) is by
  definition not in the IEEE registry — lookup is refused.
* This table is a **pruned subset** of the IEEE MA-L registry, not the whole
  registry.  ``None`` therefore means "not in this offline subset", NOT
  "unassigned prefix".  Never report an unresolved OUI as "unknown vendor" —
  report it as "not resolvable from the offline table shipped with this tool".
* MA-M (28-bit) and MA-S (36-bit) sub-assignments are deliberately NOT loaded.
  Resolving one of those against its MA-L parent block would name the wrong
  company, so we only ever claim "IEEE MA-L assignee".

Every entry below was taken verbatim from the IEEE MA-L registry
(https://standards-oui.ieee.org/oui/oui.csv) at the snapshot date recorded in
:data:`OUI_REGISTRY_SNAPSHOT`.  No prefix in this file was invented.
"""

