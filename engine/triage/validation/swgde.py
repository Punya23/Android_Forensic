def build_report(
    cases: list[ValidationCase],
    *,
    tool_name: str,
    tool_version: str,
    tester: str = "",
    dataset_name: str = "",
    dataset_provenance: str = "",
    dataset_hash: str = "",
    environment: Optional[dict[str, Any]] = None,
    purpose: str = "",
    scope: str = "",
) -> ValidationReport:
    """Assemble a :class:`ValidationReport` from executed cases.

    Anomalies (§6 field 6) and limitations (§6 field 7) are DERIVED from the cases —
    they are not accepted as parameters — so a report cannot be built that claims a
    clean run over failing cases. ``tester`` and ``dataset_name`` deliberately default
    to empty: an unattributed report must fail :func:`validate_report`, not quietly
    acquire a plausible-looking author.
    """
    anomalies: list[str] = []
    seen: set[str] = set()
    for case in cases:
        for anomaly in case.anomalies:
            text = f"[{case.case_id}] {anomaly}"
            if text not in seen:
                seen.add(text)
                anomalies.append(text)

    limitations = list(known_limitations())
    for case in cases:
        if not case.passed:
            limitations.append(
                f"[{case.case_id}] Case did not produce the expected result; the "
                f"capability it covers ({case.artifact_class}) is not demonstrated by "
                "this report and must not be relied on until re-tested."
            )

    report = ValidationReport(
        tool_name=tool_name,
        tool_version=tool_version,
        tester=tester,
        tested_at=now_iso(),
        purpose=purpose or DEFAULT_PURPOSE,
        scope=scope or DEFAULT_SCOPE,
        dataset_name=dataset_name,
        dataset_provenance=dataset_provenance,
        dataset_hash=dataset_hash,
        environment=dict(environment or {}),
        cases=list(cases),
        limitations=limitations,
        anomalies=anomalies,
        conclusion="",
    )
    report.conclusion = _build_conclusion(report)
    return report


def _build_conclusion(report: ValidationReport) -> str:
    """Generate the (tool-added, NOT 18-Q-001-mandated) conclusion from the results.

    Generated rather than hand-written so it can never contradict the case table.
    """
    total = len(report.cases)
    passed = report.passed_count()
    failed = report.failed_count()
    failed_ids = [c.case_id for c in report.cases if not c.passed]

    verdict = (
        "performed as expected for every case in this dataset"
        if failed == 0
        else "did NOT perform as expected for every case in this dataset"
    )

    return (
        f"{report.tool_name} {report.tool_version} was tested with a known dataset "
        f"(18-Q-001-2.1 Appendix A, testing type 1) over {total} case(s): {passed} "
        f"produced the expected result, {failed} did not. The tool {verdict}. "
        + (
            f"Cases not producing the expected result: {', '.join(failed_ids)}. "
            if failed_ids
            else ""
        )
        + "Per 18-Q-001-2.1 §4, 'Testing is not necessarily pass/fail' — this result "
        "is a statement about the named dataset only and asserts nothing about "
        "completeness on real device data. All standing limitations in the "
        "'Identified limitations' field apply in full and are not superseded by a "
        "passing result. This conclusion field is tool-added: SWGDE 18-Q-001-2.1 §6 "
        f"does not require a conclusion; see {SWGDE_18_Q_002} for report-level "
        "requirements."
    )


def validate_report(report: ValidationReport) -> dict[str, Any]:
    """Check a report against :data:`SWGDE_REPORT_FIELDS`.

    Returns ``{"complete": bool, "missing_required": [...], "warnings": [...]}``.
    ``complete`` means only that every required §6 field is populated. It is NOT a
    statement that the tool is validated, and the warnings list says so where relevant.
    """
    data = report.to_dict()
    missing: list[str] = []
    warnings: list[str] = []

    for spec in SWGDE_REPORT_FIELDS:
        if not spec["required"]:
            continue
        value = data.get(spec["key"])
        empty = value is None or (
            isinstance(value, (str, list, dict, tuple)) and len(value) == 0
        )
        if empty:
            missing.append(spec["key"])

    if not report.dataset_provenance:
        warnings.append(
            "dataset_provenance is empty. 18-Q-001-2.1 reference [1] (OSAC Guidelines "
            "for Data Set Development, Oct 2022) governs dataset provenance; without it "
            "the dataset cannot be independently obtained or evaluated."
        )
    if not report.dataset_hash:
        warnings.append(
            "dataset_hash is empty. Without a fixed dataset digest this test is not "
            "reproducible by a third party."
        )
    if report.failed_count() and not report.anomalies:
        warnings.append(
            f"{report.failed_count()} case(s) did not produce the expected result but "
            "no anomaly was described. 18-Q-001-2.1 §6 field 6 requires 'Results and a "
            "description of anomalies and their significance'."
        )
    if not report.conclusion:
        warnings.append(
            f"conclusion is empty. Not required by 18-Q-001-2.1 §6, but {SWGDE_18_Q_002} "
            "governs report conclusions."
        )
    if not report.reviewed_by:
        warnings.append(
            f"reviewed_by is empty: no technical review is evidenced. See {SWGDE_18_Q_002}. "
            "Technical/peer review is also named as a quality-control mitigation in "
            f"{SWGDE_12_Q_001}."
        )
    if not report.approved:
        warnings.append(
            "approved is False: this report has not been approved. Treat it as a "
            "working record, not an authorised validation."
        )
    if not report.cases:
        warnings.append(
            "No test cases are recorded. A report with no cases documents no testing "
            "whatsoever and must not be cited as evidence of validation."
        )
    # Standing warning — always true for a self-generated report, so always emitted.
    warnings.append(
        "SWGDE 18-Q-001-2.1 §5.6 (in-house developed tools): 'it is recommended that "
        "the tester be independent of the developer'. This report does not evidence "
        "tester independence, and a report generated by the tool about itself cannot."
    )

    return {
        "complete": len(missing) == 0,
        "missing_required": missing,
        "warnings": warnings,
    }


def render_report_json(report: ValidationReport) -> str:
    """The machine-readable artifact: the whole report as indented JSON."""
    payload = report.to_dict()
    payload["validation"] = validate_report(report)
    return json.dumps(payload, indent=2, ensure_ascii=False, sort_keys=False)


def render_report_html(report: ValidationReport) -> str:
    """Render the report as a fully escaped, self-contained HTML fragment.

    Every interpolated value is passed through :func:`html.escape`; case descriptions
    and anomaly text can contain arbitrary characters carved out of evidence, so none
    of it is ever trusted as markup.
    """
    esc = html.escape
    data = report.to_dict()
    checks = validate_report(report)
    parts: list[str] = []

    parts.append('<section class="swgde-validation-report">')
    parts.append("<h2>Tool validation report</h2>")
    parts.append("<p class='standard'>Documented per {}</p>".format(esc(SWGDE_18_Q_001)))

    # -- §6 fields -----------------------------------------------------------
    parts.append("<table class='fields'><tbody>")
    scalar_keys = {
        "purpose",
        "scope",
        "tool_name",
        "tool_version",
        "tester",
        "tested_at",
        "dataset_name",
        "dataset_provenance",
        "dataset_hash",
        "conclusion",
        "reviewed_by",
    }
    for spec in SWGDE_REPORT_FIELDS:
        key = spec["key"]
        if key not in scalar_keys:
            continue
        value = data.get(key) or ""
        flag = "required" if spec["required"] else "optional"
        parts.append(
            "<tr><th>{label}</th><td>{value}</td>"
            "<td class='src'>{flag} &mdash; {src}</td></tr>".format(
                label=esc(spec["label"]),
                value=esc(str(value)) if value else "<em>(not supplied)</em>",
                flag=esc(flag),
                src=esc(str(spec["source"])),
            )
        )
    parts.append(
        "<tr><th>Approved</th><td>{}</td><td class='src'>optional &mdash; "
        "tool-added</td></tr>".format("yes" if report.approved else "no")
    )
    parts.append("</tbody></table>")

    # -- environment ---------------------------------------------------------
    if report.environment:
        parts.append("<h3>Test environment</h3><ul>")
        for k, v in sorted(report.environment.items()):
            parts.append(
                "<li>{}: {}</li>".format(esc(str(k)), esc(str(_jsonable(v))))
            )
        parts.append("</ul>")

    # -- cases ---------------------------------------------------------------
    parts.append(
        "<h3>Testing procedure / scenarios and results ({p} of {t} produced the "
        "expected result)</h3>".format(p=report.passed_count(), t=len(report.cases))
    )
    parts.append(
        "<table class='cases'><thead><tr>"
        "<th>Case</th><th>Artifact class</th><th>Description</th>"
        "<th>Expected</th><th>Actual</th><th>Result</th><th>Anomalies</th>"
        "</tr></thead><tbody>"
    )
    for case in report.cases:
        d = case.to_dict()
        parts.append(
            "<tr class='{cls}'><td>{cid}</td><td>{ac}</td><td>{desc}</td>"
            "<td><pre>{exp}</pre></td><td><pre>{act}</pre></td>"
            "<td>{res}</td><td>{anom}</td></tr>".format(
                cls="passed" if case.passed else "failed",
                cid=esc(case.case_id),
                ac=esc(case.artifact_class),
                desc=esc(case.description),
                exp=esc(json.dumps(d["expected"], indent=1, ensure_ascii=False)),
                act=esc(json.dumps(d["actual"], indent=1, ensure_ascii=False)),
                res="as expected" if case.passed else "NOT as expected",
                anom=(
                    "<br>".join(esc(a) for a in case.anomalies)
                    if case.anomalies
                    else "&mdash;"
                ),
            )
        )
    parts.append("</tbody></table>")

    # -- anomalies -----------------------------------------------------------
    parts.append("<h3>Anomalies and their significance</h3>")
    if report.anomalies:
        parts.append("<ul>")
        parts.extend("<li>{}</li>".format(esc(a)) for a in report.anomalies)
        parts.append("</ul>")
    else:
        parts.append("<p>No anomalies were observed over the cases in this dataset.</p>")

    # -- limitations ---------------------------------------------------------
    parts.append("<h3>Identified limitations</h3><ul>")
    parts.extend("<li>{}</li>".format(esc(lim)) for lim in report.limitations)
    parts.append("</ul>")

    # -- completeness --------------------------------------------------------
    parts.append("<h3>Report completeness check</h3>")
    parts.append(
        "<p>Required 18-Q-001-2.1 §6 fields populated: {}</p>".format(
            "yes" if checks["complete"] else "NO"
        )
    )
    if checks["missing_required"]:
        parts.append(
            "<p class='missing'>Missing required fields: {}</p>".format(
                esc(", ".join(checks["missing_required"]))
            )
        )
    parts.append("<ul class='warnings'>")
    parts.extend("<li>{}</li>".format(esc(w)) for w in checks["warnings"])
    parts.append("</ul>")

    # -- citations -----------------------------------------------------------
    parts.append("<h3>Standards cited</h3><ul>")
    parts.extend("<li>{}</li>".format(esc(s)) for s in STANDARDS_CITED)
    parts.append("</ul>")
    parts.append("</section>")
    return "\n".join(parts)
