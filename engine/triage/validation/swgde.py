"""Machine-readable tool-validation report per SWGDE 18-Q-001-2.1 §6.

Forensic purpose
----------------
SWGDE 18-Q-001-2.1, "Minimum Requirements for Testing Tools Used in Digital and
Multimedia Forensics" (v2.1, 2024-03-07), §6 "Documentation of Testing Results" says:

    "Results of lab-based testing should be documented. Testing documentation should
    include:
      1. Purpose and scope of testing (identify tool or technique)
      2. Who performed the testing
      3. Date
      4. Testing procedure used or scenarios
      5. Datasets or other testing material used, including expected results
      6. Results and a description of anomalies and their significance
      7. Identified limitations"

That is the whole list — SEVEN fields. This module emits exactly those, plus a small
number of clearly-labelled tool-added fields, and refuses to pretend the tool-added
ones are mandated by 18-Q-001.

Limitations of this module (read before quoting its output)
-----------------------------------------------------------
1. ``conclusion``, ``reviewed_by`` and ``approved`` DO NOT APPEAR in 18-Q-001 §6. They
   are marked ``source="tool-added"`` in :data:`SWGDE_REPORT_FIELDS`; the standard that
   actually governs conclusions and technical review is SWGDE 18-Q-002, "Requirements
   for Report Writing in Digital and Multimedia Forensics" (2018-11-20).
2. ``tool_version`` is not a separate 18-Q-001 field either; §6 folds tool identity into
   field 1 ("identify tool or technique"). Emitting it explicitly is good practice, and
   it is labelled as such rather than as a requirement.
3. Dataset *provenance* is not called out by §6, which says only "datasets or other
   testing material used". Provenance guidance lives in 18-Q-001's reference [1],
   OSAC Digital Evidence, "Guidelines for Data Set Development" (Oct 2022).
4. This module produces a report; it does not confer validity. §5.6 of 18-Q-001 covers
   in-house developed tools and recommends "that the tester be independent of the
   developer". A report generated by the tool about itself does not evidence that
   independence, and :func:`validate_report` always says so in its warnings.
5. SWGDE's redistribution rule is honoured throughout: every quotation carries the
   document number and version/date.

Nothing here ever fabricates a result. :func:`build_report` derives its anomalies and
limitations from the cases it is handed; a report built from failing cases is a report
that says so.
"""

