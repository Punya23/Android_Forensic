# --- Records ------------------------------------------------------------------
@dataclass
class ValidationCase:
    """One known-answer scenario: what was expected, what actually happened.

    ``passed`` is a plain boolean recorded by whoever ran the case. Nothing in this
    module ever recomputes it into something more flattering, and ``anomalies`` is
    where the honest description of a failure lives (18-Q-001 §6 field 6).
    """

    case_id: str
    description: str
    artifact_class: str  # e.g. "hashing", "chain-of-custody", "deleted-record recovery"
    expected: dict[str, Any] = field(default_factory=dict)
    actual: dict[str, Any] = field(default_factory=dict)
    passed: bool = False
    anomalies: list[str] = field(default_factory=list)

    def to_dict(self) -> dict[str, Any]:
        return {
            "case_id": self.case_id,
            "description": self.description,
            "artifact_class": self.artifact_class,
            "expected": _jsonable(self.expected),
            "actual": _jsonable(self.actual),
            "passed": bool(self.passed),
            "anomalies": list(self.anomalies),
        }


@dataclass
class ValidationReport:
    """A complete 18-Q-001 §6 testing-results record."""

    tool_name: str
    tool_version: str
    tester: str
    tested_at: str
    purpose: str
    scope: str
    dataset_name: str
    dataset_provenance: str
    dataset_hash: str
    environment: dict[str, Any] = field(default_factory=dict)
    cases: list[ValidationCase] = field(default_factory=list)
    limitations: list[str] = field(default_factory=list)
    anomalies: list[str] = field(default_factory=list)
    conclusion: str = ""
    reviewed_by: str = ""
    approved: bool = False

    # -- derived counts ------------------------------------------------------
    def passed_count(self) -> int:
        return sum(1 for c in self.cases if c.passed)

    def failed_count(self) -> int:
        return sum(1 for c in self.cases if not c.passed)

    def to_dict(self) -> dict[str, Any]:
        return {
            "standard": SWGDE_18_Q_001,
            "standards_cited": list(STANDARDS_CITED),
            "field_definitions": [dict(f) for f in SWGDE_REPORT_FIELDS],
            "tool_name": self.tool_name,
            "tool_version": self.tool_version,
            "tester": self.tester,
            "tested_at": self.tested_at,
            "purpose": self.purpose,
            "scope": self.scope,
            "dataset_name": self.dataset_name,
            "dataset_provenance": self.dataset_provenance,
            "dataset_hash": self.dataset_hash,
            "environment": _jsonable(self.environment),
            "cases": [c.to_dict() for c in self.cases],
            "case_count": len(self.cases),
            "passed_count": self.passed_count(),
            "failed_count": self.failed_count(),
            "limitations": list(self.limitations),
            "anomalies": list(self.anomalies),
            "conclusion": self.conclusion,
            "reviewed_by": self.reviewed_by,
            "approved": bool(self.approved),
            "error_types": dict(ERROR_TYPES),
            "testing_types": dict(TESTING_TYPES),
        }


def _jsonable(value: Any) -> Any:
    """Coerce a value into something ``json.dumps`` will accept, without inventing data.

    Anything unserialisable becomes its ``repr()`` — visibly a repr, so nobody mistakes
    it for structured data that was really there.
    """
    if isinstance(value, dict):
        return {str(k): _jsonable(v) for k, v in value.items()}
    if isinstance(value, (list, tuple)):
        return [_jsonable(v) for v in value]
    if isinstance(value, (str, int, float, bool)) or value is None:
        return value
    if isinstance(value, bytes):
        # Never guess an encoding for evidence bytes; show them unambiguously.
        return {"__bytes_hex__": value.hex(), "length": len(value)}
    return repr(value)


# --- The standing disclosures -------------------------------------------------
def known_limitations() -> list[str]:
    """The verified dead-ends this tool must disclose in EVERY validation report.

    These are not hypothetical risks; each is a hard boundary confirmed against Android
    platform behaviour. They go into 18-Q-001 §6 field 7 ("Identified limitations")
    unconditionally, because omitting them would let a reader infer capabilities the
    tool does not have.
    """
    return [
        (
            "No write-blocking exists for mobile devices. There is no hardware or "
            "software write-blocker for a live Android device (SWGDE 18-F-003). Device "
            "state is recorded and every altering action is logged with "
            "alters_device=True; it is not prevented. Any claim that this tool is "
            "'read-only' would be false."
        ),
        (
            "No unallocated-space or file-slack recovery is performed, and on Android "
            "10+ with file-based encryption (FBE) none is possible: freed blocks outside "
            "a decrypted file's extent are ciphertext, so there is nothing meaningful to "
            "carve. Recovery is confined to the interior of individual SQLite database "
            "files."
        ),
        (
            "No deleted-record recovery is possible on a non-rooted device. Content "
            "providers (SMS, call log, contacts, calendar) return live rows only; the "
            "underlying database files sit in app-private storage that a non-root "
            "helper APK cannot read. Absence of a deleted record in a non-root "
            "extraction is evidence of nothing."
        ),
        (
            "Root is not decryption. On a device in the Before-First-Unlock (BFU) state "
            "the credential-encrypted (CE) storage keys are not in memory, so CE data is "
            "inaccessible even with root. 'Present but encrypted / inaccessible' is "
            "reported as exactly that, and is never collapsed into 'not found'."
        ),
        (
            "Application content protected by SQLCipher with a hardware-Keystore-wrapped "
            "key is not recoverable at any tier. This includes Signal, Threema, Session "
            "and Wickr. The key never leaves the TEE/StrongBox, so the ciphertext cannot "
            "be decrypted off-device regardless of root."
        ),
        (
            "Android framework SQLite databases are built with SECURE_DELETE and "
            "AUTOVACUUM enabled. Freed pages are zeroed and returned to the operating "
            "system, so the freelist yield from telephony, contacts and call-log "
            "databases is near zero. A nil recovery result from these databases is the "
            "expected outcome and must not be read as proof that nothing was deleted."
        ),
        (
            "No characterised error rate has been established for this tool. Per SWGDE "
            "12-Q-001 v2.0, digital forensics is far more prone to systematic than "
            "random errors, so confidence rests on error mitigation analysis — known "
            "limitations, quality control, and corroboration — rather than on a "
            "statistical error rate. No error rate should be quoted from this report "
            "because none has been measured."
        ),
        (
            "This tool performs a logical acquisition only. It creates no device image, "
            "performs no physical or chip-off acquisition, and has no image-file ingest "
            "mode. Findings are a field-triage preview and are not a substitute for a "
            "full laboratory examination (NIST SP 800-101r1 §4.5)."
        ),
        (
            "As an in-house developed tool (18-Q-001-2.1 §5.6), re-testing is required "
            "'At first use and all tool revisions', and §5.6 recommends 'that the tester "
            "be independent of the developer'. A report generated by the tool about "
            "itself does not satisfy that recommendation."
        ),
    ]


